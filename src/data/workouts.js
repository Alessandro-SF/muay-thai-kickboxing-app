/**
 * Guided workout library.
 *
 * Schema (all times in seconds):
 *  id, title, category, discipline ('muay-thai' | 'kickboxing'), level, duration (nominal minutes)
 *  description, focus (short text), equipment[], objectives[]
 *  roundSeconds, restSeconds, prepSeconds
 *  pace          optional seconds between combination callouts (defaults by level)
 *  media         optional { video, cover } — reserved for future instructional media
 *  rounds[]      each round is one of:
 *    { title, mode: 'combos', focus: [...tags], instruction }
 *    { title, mode: 'tips', instruction, tips: [...] }           freestyle with coaching tips
 *    { title, mode: 'blocks', blocks: [{ seconds, label, cue, mode?, focus? }] }
 *  A round may override `seconds`.
 *
 * Focus tags: boxing, kicks, teeps, knees, elbows, defense, footwork, clinch, mixed.
 */

